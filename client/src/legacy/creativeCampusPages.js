export function initTransportCreativePage() {
  const root = document.querySelector('.siet-formal-transport');
  if (!root) return;

  // 1. Corridor Tabs Switching
  const tabs = root.querySelectorAll('.sft-tab-btn');
  const panels = root.querySelectorAll('.sft-corridor-panel');

  tabs.forEach(tab => {
    tab.addEventListener('click', () => {
      tabs.forEach(t => t.classList.remove('is-active'));
      tab.classList.add('is-active');

      const targetTab = tab.dataset.tab;
      panels.forEach(panel => {
        if (panel.dataset.panel === targetTab) {
          panel.classList.add('is-active');
        } else {
          panel.classList.remove('is-active');
        }
      });
    });
  });

  // 2. Quick Route & Stop Search
  const searchInput = root.querySelector('#sft-route-input');
  const routeRows = root.querySelectorAll('.sft-route-row');
  const emptyState = root.querySelector('#sft-search-empty');

  searchInput?.addEventListener('input', () => {
    const q = (searchInput.value || '').trim().toLowerCase();
    let totalMatches = 0;

    if (!q) {
      routeRows.forEach(row => { row.style.display = ''; });
      if (emptyState) emptyState.hidden = true;
      return;
    }

    // When searching, make all panels visible so user sees matches anywhere
    panels.forEach(p => p.classList.add('is-active'));
    tabs.forEach(t => t.classList.remove('is-active'));

    routeRows.forEach(row => {
      const text = row.dataset.search || '';
      if (text.includes(q)) {
        row.style.display = '';
        totalMatches++;
      } else {
        row.style.display = 'none';
      }
    });

    if (emptyState) {
      emptyState.hidden = totalMatches > 0;
    }
  });

  // 3. Print Schedule
  const printBtn = root.querySelector('.js-print-roster-btn');
  printBtn?.addEventListener('click', () => {
    window.print();
  });
}

