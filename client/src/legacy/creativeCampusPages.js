export function initTransportCreativePage() {
  const root = document.querySelector('.siet-formal-transport');
  if (!root) return;

  const PAGE_SIZE = 15;
  let currentPage = 1;
  let currentCorridor = 'all';
  let searchQuery = '';
  let currentView = 'grid'; // 'grid' | 'table'

  const gridView = root.querySelector('#sft-buses-grid-view');
  const tableView = root.querySelector('#sft-buses-table-view');
  const tableBody = root.querySelector('#sft-buses-table-body');
  const paginationContainer = root.querySelector('#sft-pagination-container');
  const emptyState = root.querySelector('#sft-search-empty');
  const searchInput = root.querySelector('#sft-route-input');
  const clearSearchBtn = root.querySelector('#sft-clear-search-btn');
  const tabs = root.querySelectorAll('.sft-tab-btn');
  const viewBtns = root.querySelectorAll('.sft-view-btn');
  const activeTitle = root.querySelector('#sft-active-title');
  const activeDesc = root.querySelector('#sft-active-desc');
  const activeBadge = root.querySelector('#sft-active-badge');

  function renderBusCard(r) {
    return `
      <article class="sft-bus-card" data-bus-num="${r.busNum}">
        <div class="sft-bus-card-header">
          <strong class="sft-route-code">${r.no}</strong>
          <div class="sft-bus-meta-badges">
            <span class="sft-bus-plate">${r.busPlate}</span>
            <span class="sft-bus-capacity">54 Seater</span>
          </div>
        </div>
        <h4 class="sft-bus-card-title">${r.name}</h4>
        <div class="sft-bus-stops-box">
          <span class="sft-stops-icon" aria-hidden="true">📍</span>
          <div class="sft-stops-content">
            <span class="sft-stops-label">Boarding Waypoints &amp; Towns</span>
            <p class="sft-stops-text">${r.stops}</p>
          </div>
        </div>
        <div class="sft-bus-card-footer">
          <div class="sft-timing-badge">
            <span>🕒 ${r.morningTime}</span>
          </div>
          <div class="sft-driver-text">
            <span>👨‍✈️ Driver: <strong>${r.driver}</strong></span>
          </div>
        </div>
      </article>
    `;
  }

  function renderBusRow(r) {
    return `
      <tr class="sft-route-row" data-bus-num="${r.busNum}">
        <td><strong class="sft-route-code">${r.no}</strong></td>
        <td><b>${r.name}</b><br><small style="color:#64748b; font-weight:600;">${r.busPlate} · 54 Seater</small></td>
        <td><span class="sft-stops-text">${r.stops}</span></td>
        <td><span class="sft-timing-badge">${r.morningTime}</span></td>
        <td><small class="sft-driver-text">👨‍✈️ ${r.driver}</small></td>
      </tr>
    `;
  }

  function getFilteredBuses() {
    let list = all37Buses;
    if (currentCorridor !== 'all') {
      list = list.filter(b => b.corridorId === currentCorridor);
    }
    if (searchQuery) {
      const q = searchQuery.toLowerCase();
      list = list.filter(r => {
        const text = `bus ${r.busNum} bus ${r.busNumPadded} ${r.busNum} ${r.no.toLowerCase()} route ${r.busNum} route ${r.busNumPadded} ${r.name.toLowerCase()} ${r.stops.toLowerCase()} ${r.driver.toLowerCase()} ${r.busPlate.toLowerCase()}`;
        return text.includes(q);
      });
    }
    return list;
  }

  function renderPagination(totalItems, page) {
    if (!paginationContainer) return;
    const totalPages = Math.ceil(totalItems / PAGE_SIZE) || 1;
    if (totalItems === 0) {
      paginationContainer.innerHTML = '';
      return;
    }

    const startItem = (page - 1) * PAGE_SIZE + 1;
    const endItem = Math.min(page * PAGE_SIZE, totalItems);

    let pages = [];
    if (totalPages <= 7) {
      for (let i = 1; i <= totalPages; i++) pages.push(i);
    } else {
      pages.push(1);
      if (page > 3) pages.push('...');
      let start = Math.max(2, page - 1);
      let end = Math.min(totalPages - 1, page + 1);
      if (page <= 3) {
        start = 2;
        end = 4;
      } else if (page >= totalPages - 2) {
        start = totalPages - 3;
        end = totalPages - 1;
      }
      for (let i = start; i <= end; i++) {
        pages.push(i);
      }
      if (page < totalPages - 2) pages.push('...');
      pages.push(totalPages);
    }

    const prevDisabled = page <= 1;
    const nextDisabled = page >= totalPages;

    paginationContainer.innerHTML = `
      <div class="sft-pagination-bar">
        <div class="sft-pagination-summary">
          Showing <strong>${startItem}–${endItem}</strong> of <strong>${totalItems}</strong> buses &nbsp;·&nbsp; Page <strong>${page}</strong> of <strong>${totalPages}</strong>
        </div>
        <div class="sft-pagination-controls" role="navigation" aria-label="Bus Fleet Pagination">
          <button type="button" class="sft-page-nav-btn sft-page-prev ${prevDisabled ? 'disabled' : ''}" data-page="${page - 1}" ${prevDisabled ? 'disabled' : ''} aria-label="Previous Page">
            <svg width="15" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round"><polyline points="15 18 9 12 15 6"></polyline></svg>
            <span>Previous</span>
          </button>
          <div class="sft-page-numbers">
            ${pages.map(p => {
              if (p === '...') {
                return `<span class="sft-page-dots" aria-hidden="true">…</span>`;
              }
              const isActive = p === page;
              return `
                <button type="button" class="sft-page-num-btn ${isActive ? 'is-active' : ''}" data-page="${p}" ${isActive ? 'aria-current="page"' : ''} aria-label="Page ${p}">
                  ${p}
                </button>
              `;
            }).join('')}
          </div>
          <button type="button" class="sft-page-nav-btn sft-page-next ${nextDisabled ? 'disabled' : ''}" data-page="${page + 1}" ${nextDisabled ? 'disabled' : ''} aria-label="Next Page">
            <span>Next</span>
            <svg width="15" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round"><polyline points="9 18 15 12 9 6"></polyline></svg>
          </button>
        </div>
      </div>
    `;

    // Attach click events to pagination controls
    paginationContainer.querySelectorAll('[data-page]').forEach(btn => {
      btn.addEventListener('click', (e) => {
        e.preventDefault();
        const targetPage = parseInt(btn.dataset.page, 10);
        if (targetPage && targetPage !== currentPage && targetPage >= 1 && targetPage <= totalPages) {
          goToPage(targetPage, true);
        }
      });
    });
  }

  function goToPage(page, shouldScroll) {
    const list = getFilteredBuses();
    const totalPages = Math.ceil(list.length / PAGE_SIZE) || 1;
    currentPage = Math.min(Math.max(1, page), totalPages);

    const startIndex = (currentPage - 1) * PAGE_SIZE;
    const pageBuses = list.slice(startIndex, startIndex + PAGE_SIZE);

    if (list.length === 0) {
      if (gridView) gridView.innerHTML = '';
      if (tableBody) tableBody.innerHTML = '';
      if (emptyState) emptyState.hidden = false;
      if (paginationContainer) paginationContainer.innerHTML = '';
      return;
    }

    if (emptyState) emptyState.hidden = true;

    // Render Grid View
    if (gridView) {
      gridView.innerHTML = pageBuses.map(renderBusCard).join('');
    }

    // Render Table View
    if (tableBody) {
      tableBody.innerHTML = pageBuses.map(renderBusRow).join('');
    }

    // Render Pagination
    renderPagination(list.length, currentPage);

    // Smooth scroll back to top of bus section if requested
    if (shouldScroll) {
      const section = document.getElementById('areas-covered');
      if (section) {
        const offset = -75;
        const bodyRect = document.body.getBoundingClientRect().top;
        const elementRect = section.getBoundingClientRect().top;
        const elementPosition = elementRect - bodyRect;
        const offsetPosition = elementPosition + offset;
        window.scrollTo({
          top: Math.max(0, offsetPosition),
          behavior: 'smooth'
        });
      }
    }
  }

  function updateCorridorHeader() {
    const corridor = transportCorridors.find(c => c.id === currentCorridor) || transportCorridors[0];
    if (searchQuery) {
      const list = getFilteredBuses();
      if (activeTitle) activeTitle.textContent = `Search Results (${list.length} bus${list.length === 1 ? '' : 'es'} found)`;
      if (activeDesc) activeDesc.textContent = `Showing verified matches for query "${searchQuery}". Clear search to view standard corridor routes.`;
      if (activeBadge) activeBadge.textContent = `${list.length} Bus${list.length === 1 ? '' : 'es'}`;
    } else {
      if (activeTitle) activeTitle.textContent = corridor.name;
      if (activeDesc) activeDesc.textContent = corridor.desc;
      if (activeBadge) activeBadge.textContent = corridor.badge;
    }
  }

  // 1. Corridor Tabs Switching
  tabs.forEach(tab => {
    tab.addEventListener('click', () => {
      tabs.forEach(t => t.classList.remove('is-active'));
      tab.classList.add('is-active');
      currentCorridor = tab.dataset.tab || 'all';
      currentPage = 1;
      updateCorridorHeader();
      goToPage(1, false);
    });
  });

  // 2. Search Handler
  searchInput?.addEventListener('input', () => {
    searchQuery = (searchInput.value || '').trim();
    currentPage = 1;
    updateCorridorHeader();
    goToPage(1, false);
  });

  clearSearchBtn?.addEventListener('click', () => {
    if (searchInput) searchInput.value = '';
    searchQuery = '';
    currentCorridor = 'all';
    tabs.forEach(t => t.classList.toggle('is-active', t.dataset.tab === 'all'));
    currentPage = 1;
    updateCorridorHeader();
    goToPage(1, false);
  });

  // 3. View Switcher (Grid vs Table)
  viewBtns.forEach(btn => {
    btn.addEventListener('click', () => {
      const view = btn.dataset.view;
      if (view === currentView) return;
      currentView = view;
      viewBtns.forEach(b => b.classList.remove('is-active'));
      btn.classList.add('is-active');

      if (view === 'grid') {
        if (gridView) gridView.style.display = 'grid';
        if (tableView) tableView.style.display = 'none';
      } else {
        if (gridView) gridView.style.display = 'none';
        if (tableView) tableView.style.display = 'block';
      }
    });
  });

  // 4. Print Official Schedule
  const printBtn = root.querySelector('.js-print-roster-btn');
  printBtn?.addEventListener('click', () => {
    window.print();
  });

  // Initial Boot
  updateCorridorHeader();
  goToPage(1, false);
}

