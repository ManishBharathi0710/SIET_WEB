export function initEntrepreneurshipEvents() {
  const activateTab = (targetTab) => {
    const tabLinks = document.querySelectorAll('.siet-edc-side-tab');
    const panels = document.querySelectorAll('.siet-edc-panel');

    tabLinks.forEach(b => {
      const isMatch = b.dataset.tab === targetTab;
      b.classList.toggle('is-active', isMatch);
      if (isMatch) b.setAttribute('aria-current', 'page');
      else b.removeAttribute('aria-current');
    });

    panels.forEach(p => {
      const isMatch = p.id === `edc-panel-${targetTab}`;
      p.classList.toggle('is-active', isMatch);
      if (isMatch) {
        p.querySelectorAll('.reveal').forEach(el => el.classList.add('is-visible'));
      }
    });
  };

  // 1. Sidebar Tab Click Handlers
  const tabLinks = document.querySelectorAll('.siet-edc-side-tab');
  tabLinks.forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const targetTab = btn.dataset.tab;
      if (!targetTab) return;

      activateTab(targetTab);

      // Cleanly update URL without triggering window.hashchange or destroying top header nav
      if (window.history && window.history.replaceState) {
        window.history.replaceState(null, '', `#/placements/entrepreneurship?tab=${targetTab}`);
      }

      const mainEl = document.querySelector('.siet-vm-main');
      if (mainEl && window.innerWidth < 992) {
        mainEl.scrollIntoView({ behavior: 'smooth', block: 'start' });
      }
    });
  });

  // Check URL query param for default tab
  const hash = window.location.hash || '';
  if (hash.includes('?tab=')) {
    const tabMatch = hash.match(/\?tab=([a-z0-9_-]+)/);
    if (tabMatch && tabMatch[1]) {
      activateTab(tabMatch[1]);
    }
  }

  // Support browser Back/Forward navigation
  window.addEventListener('popstate', () => {
    const currentHash = window.location.hash || '';
    const tabMatch = currentHash.match(/\?tab=([a-z0-9_-]+)/);
    if (tabMatch && tabMatch[1]) {
      activateTab(tabMatch[1]);
    } else {
      activateTab('about');
    }
  });

  // Handle CTA switch tab buttons
  document.querySelectorAll('.siet-edc-switch-tab-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const target = btn.dataset.targetTab;
      if (target) {
        activateTab(target);
        if (window.history && window.history.replaceState) {
          window.history.replaceState(null, '', `#/placements/entrepreneurship?tab=${target}`);
        }
      }
    });
  });

  // 2. Startups Search & Category Filtering
  const searchInput = document.getElementById('edc-startup-search');
  const filterBtns = document.querySelectorAll('.edc-filter-chip');
  const startupItems = document.querySelectorAll('.siet-startup-cb-card');
  const emptyState = document.getElementById('edc-startups-empty');

  let activeCategory = 'all';
  let activeSearch = '';

  const applyStartupFilters = () => {
    let visibleCount = 0;
    startupItems.forEach(item => {
      const cat = item.dataset.category || '';
      const searchText = item.dataset.search || '';

      const matchesCat = (activeCategory === 'all') || (cat === activeCategory);
      const matchesSearch = !activeSearch || searchText.includes(activeSearch);

      const isVisible = matchesCat && matchesSearch;
      item.style.setProperty('display', isVisible ? 'flex' : 'none', 'important');
      if (isVisible) visibleCount++;
    });

    if (emptyState) {
      emptyState.style.display = visibleCount === 0 ? 'block' : 'none';
    }
  };

  filterBtns.forEach(btn => {
    btn.addEventListener('click', () => {
      filterBtns.forEach(b => b.classList.toggle('is-active', b === btn));
      activeCategory = btn.dataset.filter || 'all';
      applyStartupFilters();
    });
  });

  if (searchInput) {
    searchInput.addEventListener('input', (e) => {
      activeSearch = (e.target.value || '').trim().toLowerCase();
      applyStartupFilters();
    });
  }

  // 3. Events Table Search & Year Filtering
  const eventSearchInput = document.getElementById('edc-events-search');
  const eventYearBtns = document.querySelectorAll('.edc-event-year-chip');
  const eventRows = document.querySelectorAll('#edc-events-tbody .edc-event-row');
  const eventsEmptyState = document.getElementById('edc-events-empty');

  let activeEventYear = 'all';
  let activeEventSearch = '';

  const applyEventFilters = () => {
    let visibleCount = 0;
    eventRows.forEach(row => {
      const yr = row.dataset.year || '';
      const searchText = row.dataset.search || '';

      const matchesYear = (activeEventYear === 'all') || (yr === activeEventYear);
      const matchesSearch = !activeEventSearch || searchText.includes(activeEventSearch);

      const isVisible = matchesYear && matchesSearch;
      row.style.setProperty('display', isVisible ? 'table-row' : 'none', 'important');
      if (isVisible) visibleCount++;
    });

    if (eventsEmptyState) {
      eventsEmptyState.style.display = visibleCount === 0 ? 'block' : 'none';
    }
  };

  eventYearBtns.forEach(btn => {
    btn.addEventListener('click', () => {
      eventYearBtns.forEach(b => b.classList.toggle('is-active', b === btn));
      activeEventYear = btn.dataset.year || 'all';
      applyEventFilters();
    });
  });

  if (eventSearchInput) {
    eventSearchInput.addEventListener('input', (e) => {
      activeEventSearch = (e.target.value || '').trim().toLowerCase();
      applyEventFilters();
    });
  }

  // 4. Startup Item Click -> Open Lightbox Modal
  const modal = document.getElementById('siet-startup-modal');
  const modalBody = document.getElementById('siet-sm-body');

  const openStartupModal = (startup) => {
    if (!modal || !modalBody) return;
    modalBody.innerHTML = `
      <div class="modal-startup-header">
        <span class="modal-cat-tag ${startup.category}">${startup.categoryLabel}</span>
        <span class="modal-loc-tag">${startup.location}</span>
      </div>
      <h2 class="modal-startup-name">${startup.shortName}</h2>
      <div class="modal-verbatim-box">
        ${startup.verbatimHtml}
      </div>
      <div class="modal-meta-grid" style="margin-top:16px;">
        <div class="modal-meta-cell">
          <span class="lbl">Department:</span>
          <span class="val">${startup.dept}</span>
        </div>
        <div class="modal-meta-cell">
          <span class="lbl">Recognition:</span>
          <span class="val highlight">${startup.highlight}</span>
        </div>
      </div>
    `;
    modal.style.display = 'flex';
    modal.setAttribute('aria-hidden', 'false');
    document.body.style.overflow = 'hidden';
  };

  startupItems.forEach((item, index) => {
    item.addEventListener('click', () => {
      const startup = startupsData[index];
      if (startup) openStartupModal(startup);
    });

    item.addEventListener('keydown', (e) => {
      if (e.key === 'Enter' || e.key === ' ') {
        e.preventDefault();
        const startup = startupsData[index];
        if (startup) openStartupModal(startup);
      }
    });
  });

  // Modal Close Handlers
  document.querySelectorAll('.js-close-startup-modal').forEach(el => {
    el.addEventListener('click', () => {
      if (modal) {
        modal.style.display = 'none';
        modal.setAttribute('aria-hidden', 'true');
        document.body.style.overflow = '';
      }
    });
  });
}
